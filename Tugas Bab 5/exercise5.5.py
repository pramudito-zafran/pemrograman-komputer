# Versi If
warnaAlien = 'hijau'
if warnaAlien == 'hijau' :
    print("Selamat, kamu mendapatkan 5 poin")
elif warnaAlien == 'kuning' :
    print("Selamat, kamu mendapatkan 10 poin")
else :
    print("Selamat, kamu mendapatkan 15 poin")


