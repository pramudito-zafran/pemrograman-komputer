def show_messages(messages):
    """Mencetak setiap pesan teks dari sebuah daftar."""
    for message in messages:
        print(message)

# Mendefinisikan daftar berisi pesan-pesan teks pendek
text_messages = ["Halo, gimana kabarnya?", "Bagaimana belajarnya?", "Jangan lupa latihan Python broo", "Sampai jumpa nanti!"]

# Memanggil fungsi untuk menampilkan semua pesan
show_messages(text_messages)
